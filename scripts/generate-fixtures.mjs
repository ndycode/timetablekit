function standardOptions() {
  return { locale: "en-PH", timezone: TIMEZONE, evidence: "none" };
}

function weekly(title, weekdays, startTime, endTime, extras = {}, range) {
  return {
    title,
    schedule: { kind: "weekly", weekdays, ...(range ?? {}) },
    startTime,
    endTime,
    timezone: TIMEZONE,
    ...extras,
  };
}

function exact(title, exactDates, startTime, endTime, extras = {}) {
  return {
    title,
    schedule: { kind: "exact", exactDates },
    startTime,
    endTime,
    timezone: TIMEZONE,
    ...extras,
  };
}

function conflict(occurrence, startsAt, endsAt) {
  return { occurrence, overlap: { startsAt, endsAt } };
}

function fixture(
  id,
  kind,
  input,
  events,
  options = standardOptions(),
  extras = {},
) {
  const extension = kind === "csv" ? "csv" : "txt";
  return {
    id,
    kind,
    input,
    filename: `${id}.${extension}`,
    options,
    events,
    warningCodes: [],
    conflicts: [],
    ...extras,
  };
}

function binaryFixture(id, kind, sourceText, events, extras = {}) {
  const extension = kind === "image" ? "png" : "pdf";
  return {
    id,
    kind,
    sourceText,
    filename: `${id}.${extension}`,
    options: standardOptions(),
    events,
    warningCodes: [],
    conflicts: [],
    ...extras,
  };
}

