function manifestFor(definition) {
  const extension =
    definition.kind === "text"
      ? "txt"
      : definition.kind === "csv"
        ? "csv"
        : definition.kind === "image"
          ? "png"
          : "pdf";
  return {
    id: definition.id,
    title: definition.id.replace(/-/g, " "),
    synthetic: true,
    visibility: "public",
    kind: definition.kind,
    input: `inputs/${definition.id}.${extension}`,
    expected: `expected/${definition.id}.json`,
    filename: definition.filename,
    ...(definition.delimiter === undefined
      ? {}
      : { delimiter: definition.delimiter }),
    options: definition.options,
    ...(definition.artifact === undefined
      ? {}
      : { artifact: definition.artifact }),
    ...(definition.ocrWarningCodes === undefined
      ? {}
      : { ocrWarningCodes: definition.ocrWarningCodes }),
    ...(definition.pageCount === undefined
      ? {}
      : { pageCount: definition.pageCount }),
    provenance: PROVENANCE,
  };
}

function expectedFor(definition) {
  const source = {
    kind: definition.kind,
    filename: definition.filename,
    ...(definition.kind === "image" ? { mimeType: "image/png" } : {}),
    ...(definition.kind === "pdf" ? { mimeType: "application/pdf" } : {}),
    pageCount: definition.pageCount ?? 1,
  };
  return {
    format: "timetablekit-normalized-v1",
    source,
    timezone: definition.options.timezone,
    locale: definition.options.locale,
    events: definition.events,
    warningCodes: [...definition.warningCodes].sort(),
    conflicts: definition.conflicts,
  };
}

async function jsonText(value) {
  return prettier.format(JSON.stringify(value), { parser: "json" });
}

export async function renderFixture(definition) {
  const extension =
    definition.kind === "text"
      ? "txt"
      : definition.kind === "csv"
        ? "csv"
        : definition.kind === "image"
          ? "png"
          : "pdf";
  return {
    manifestPath: `manifests/${definition.id}.json`,
    inputPath: `inputs/${definition.id}.${extension}`,
    expectedPath: `expected/${definition.id}.json`,
    manifestText: await jsonText(manifestFor(definition)),
    inputText: definition.input,
    expectedText: await jsonText(expectedFor(definition)),
  };
}

function svgFor(definition) {
  const source = Array.isArray(definition.sourceText)
    ? definition.sourceText.join("\n")
    : definition.sourceText;
  const lines = source.split("\n");
  const isGrid = definition.artifact === "image-grid";
  const fill = definition.id === "image-list-ocr-noise" ? "#777777" : "#222222";
  const lineHeight = isGrid ? 42 : 36;
  const width = isGrid ? 1400 : 1200;
  const height = Math.max(420, 160 + lines.length * lineHeight);
  const escaped = lines
    .map(
      (line, index) =>
        `<text x="56" y="${120 + index * lineHeight}" font-family="Arial, sans-serif" font-size="${isGrid ? 27 : 30}" fill="${fill}">${line.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;")}</text>`,
    )
    .join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}"><rect width="100%" height="100%" fill="#ffffff"/><rect x="26" y="26" width="${width - 52}" height="${height - 52}" fill="none" stroke="#b7c0c8" stroke-width="2"/>${escaped}</svg>`;
}

async function imageBytes(definition) {
  return sharp(Buffer.from(svgFor(definition)))
    .png({ compressionLevel: 9, adaptiveFiltering: false })
    .toBuffer();
}

function pdfTextPages(definition) {
  if (Array.isArray(definition.sourceText)) return definition.sourceText;
  return [definition.sourceText];
}

async function pdfBytes(definition) {
  const pdf = await PDFDocument.create();
  pdf.setTitle(definition.id);
  pdf.setAuthor("TimetableKit synthetic fixture generator");
  pdf.setCreator("TimetableKit synthetic fixture generator");
  pdf.setProducer("TimetableKit");
  const fixedDate = new Date("2026-09-01T00:00:00.000Z");
  pdf.setCreationDate(fixedDate);
  pdf.setModificationDate(fixedDate);
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  if (definition.artifact === "pdf-scanned") {
    const image = await pdf.embedPng(await imageBytes(definition));
    for (let index = 0; index < (definition.pageCount ?? 1); index += 1) {
      const page = pdf.addPage([1200, 700]);
      page.drawImage(image, { x: 0, y: 0, width: 1200, height: 700 });
    }
  } else {
    for (const pageText of pdfTextPages(definition)) {
      const page = pdf.addPage([612, 792]);
      page.drawText(pageText, {
        x: 48,
        y: 720,
        size: 13,
        lineHeight: 24,
        font,
        color: rgb(0.1, 0.1, 0.1),
        maxWidth: 516,
      });
    }
  }
  return Buffer.from(
    await pdf.save({ useObjectStreams: false, addDefaultPage: false }),
  );
}

export async function renderBinaryFixture(definition) {
  return definition.kind === "image"
    ? imageBytes(definition)
    : pdfBytes(definition);
}

export async function generateFixtures() {
  await Promise.all([
    mkdir(resolve(fixturesRoot, "manifests"), { recursive: true }),
    mkdir(resolve(fixturesRoot, "inputs"), { recursive: true }),
    mkdir(resolve(fixturesRoot, "expected"), { recursive: true }),
  ]);
  for (const definition of allFixtureDefinitions) {
    const rendered = await renderFixture(definition);
    const input =
      definition.kind === "text" || definition.kind === "csv"
        ? rendered.inputText
        : await renderBinaryFixture(definition);
    await Promise.all([
      writeFile(
        resolve(fixturesRoot, rendered.manifestPath),
        rendered.manifestText,
        "utf8",
      ),
      writeFile(resolve(fixturesRoot, rendered.inputPath), input),
      writeFile(
        resolve(fixturesRoot, rendered.expectedPath),
        rendered.expectedText,
        "utf8",
      ),
    ]);
  }
  console.log(
    `Generated ${allFixtureDefinitions.length} synthetic fixture manifests, inputs, and expected outputs.`,
  );
}

if (
  process.argv[1] !== undefined &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await generateFixtures();
}
